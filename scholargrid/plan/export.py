"""Plan exports: Markdown (with labelled computed sections), JSON, BibTeX, and a supervisor email draft."""
from __future__ import annotations

from datetime import datetime
from typing import Dict, List

from ..bibtex import to_bibtex
from .schemas import PlanDocument


def _ref_link(doc: PlanDocument, rid: str) -> str:
    r = next((x for x in doc.references if x["rid"] == rid), None)
    return f"[{rid}]({r['url']})" if r and r.get("url") else rid


def plan_to_markdown(doc: PlanDocument) -> str:
    p, g = doc.plan, doc.gap_snapshot
    nov = g.get("novelty") or {}
    checked = (datetime.fromtimestamp(nov["checked_at"]).strftime("%Y-%m-%d") if nov.get("checked_at") else "not checked")
    L: List[str] = [f"# {p.title}", "",
                    f"**The gap:** {g.get('title', '')} — {g.get('statement', '')}",
                    f"*Novelty check: {str(nov.get('status', 'not_checked')).replace('_', ' ')} "
                    f"({nov.get('scope', 'none')}, {checked}).*", "",
                    "## Research question", p.research_question, ""]
    for head, items in (("Sub-questions", p.sub_questions), ("Hypotheses", p.hypotheses)):
        if items:
            L += [f"## {head}", *[f"- {x}" for x in items], ""]
    L += ["## Why it matters", p.why_it_matters, "", "## Method sketch", p.method_sketch, ""]
    for head, choices in (("Baselines", p.baselines), ("Datasets", p.datasets)):
        L += [f"## {head}", "", "| Name | Why | Reference |", "|---|---|---|"]
        L += [f"| {c.name} | {c.why} | {_ref_link(doc, c.ref)} |" for c in choices] or ["| — | none chosen | |"]
        L.append("")
    if p.metrics:
        L += ["## Metrics", *[f"- {m}" for m in p.metrics], ""]
    if p.experiments:
        L += ["## Experiments", *[f"- {e}" for e in p.experiments], ""]
    L += ["## Minimum viable result", p.minimum_viable_result, ""]
    if p.stretch_goals:
        L += ["## Stretch goals", *[f"- {s}" for s in p.stretch_goals], ""]
    L += ["## Milestones", "", "| Weeks | Goal | Tasks | Deliverable |", "|---|---|---|---|"]
    L += [f"| {m.weeks} | {m.goal} | {'; '.join(m.tasks)} | {m.deliverable} |" for m in p.milestones]
    L += ["", "## Risks", "", "| Risk | Mitigation |", "|---|---|"]
    L += [f"| {r.risk} | {r.mitigation} |" for r in p.risks]
    L += ["", "## Skills to learn", *[f"- {s}" for s in p.skills_to_learn], "",
          "## Compute", p.compute_estimate, "",
          "## Questions for a supervisor", *[f"- {q}" for q in p.questions_for_supervisor], ""]
    c: Dict = doc.computed
    L += ["## Computed from the referenced papers", "",
          "*Most frequent authors among the papers this plan builds on (not a ranking of researchers):*"]
    L += [f"- {('[' + x['name'] + '](' + x['url'] + ')') if x.get('url') else x['name']} ({x['papers']} papers)"
          for x in c.get("people", [])] or ["- none found"]
    L += ["", "*Venues of the referenced papers:*"]
    L += [f"- {v} ({n})" for v, n in c.get("venues", [])] or ["- no venue data"]
    L += ["", "*Code links:*"]
    L += [f"- [{x['title']}]({x['code_url']})" for x in c.get("code_links", [])] or ["- none listed"]
    L += ["", "## References", ""]
    L += [f"- **{r['rid']}** [{r['title']}]({r['url']}) ({r.get('year') or 'n.d.'}) — {r.get('role', '')}"
          for r in doc.references]
    when = datetime.fromtimestamp(doc.created_at).strftime("%Y-%m-%d")
    L += ["", "---", f"Generated by ScholarGrid on {when} ({doc.generated_by.get('mode', 'template')}). "
          "Verify every reference before relying on it."]
    return "\n".join(L) + "\n"


def plan_to_json(doc: PlanDocument) -> str:
    return doc.model_dump_json(indent=2)


def plan_to_bibtex(doc: PlanDocument) -> str:
    rows = []
    for r in doc.references:
        pid = str(r.get("paper_id", ""))
        is_arxiv = bool(r.get("in_corpus")) or ("." in pid and not pid.startswith("W"))
        rows.append({"paper_id": pid, "arxiv_id": pid if is_arxiv else "", "title": r.get("title", ""),
                     "date": str(r.get("year") or ""), "url": r.get("url", ""), "authors": ""})
    return to_bibtex(rows)


def supervisor_email(doc: PlanDocument) -> str:
    p, g = doc.plan, doc.gap_snapshot
    steps = [m.goal for m in p.milestones][:3]
    weeks = doc.inputs.get("weeks", "")
    bullets = "\n".join(f"- {s[:110]}" for s in steps)
    return (f"Subject: Possible project: {p.title[:70]}\n\n"
            f"Dear [name],\n\n"
            f"I found an open problem in the literature: {str(g.get('statement', ''))[:220]}\n\n"
            f"My question would be: {p.research_question[:200]}\n\n"
            f"A {weeks}-week plan:\n{bullets}\n\n"
            f"Could we meet briefly to discuss whether this is worth pursuing?\n\n"
            f"Best regards,\n[your name]\n")
